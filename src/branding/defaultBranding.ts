export function normalizeBranding(value?: Partial<BrandingSettings>): BrandingSettings {
  return {
    ...defaultBranding,
    ...value,
    logos: {
      ...defaultBranding.logos,
      ...value?.logos,
      primary: { ...defaultBranding.logos.primary, ...value?.logos?.primary },
      epunemi: { ...defaultBranding.logos.epunemi, ...value?.logos?.epunemi },
      institutional: { ...defaultBranding.logos.institutional, ...value?.logos?.institutional },
    },
    colors: { ...defaultBranding.colors, ...value?.colors },
    header: { ...defaultBranding.header, ...value?.header },
    presentation: {
      ...defaultBranding.presentation,
      ...value?.presentation,
      homeWinnerCard: { ...defaultBranding.presentation.homeWinnerCard, ...value?.presentation?.homeWinnerCard },
      winnerView: { ...defaultBranding.presentation.winnerView, ...value?.presentation?.winnerView },
    },
  }
}
